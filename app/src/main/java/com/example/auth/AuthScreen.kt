@Composable
fun EditorialCrestBanner() {
    val primaryColor = MaterialTheme.colorScheme.primary
    val goldColor = MaterialTheme.colorScheme.tertiary
    val surfaceVariant = MaterialTheme.colorScheme.surfaceVariant

    Box(
        modifier = Modifier
            .size(92.dp)
            .clip(CircleShape)
            .background(
                Brush.radialGradient(
                    colors = listOf(surfaceVariant, MaterialTheme.colorScheme.surface)
                )
            )
            .border(1.5.dp, goldColor.copy(alpha = 0.6f), CircleShape),
        contentAlignment = Alignment.Center
    ) {
        Canvas(modifier = Modifier.fillMaxSize()) {
            val center = Offset(size.width / 2f, size.height / 2f)
            drawCircle(
                color = primaryColor.copy(alpha = 0.12f),
                radius = size.minDimension * 0.38f,
                center = center
            )
            drawCircle(
                color = goldColor.copy(alpha = 0.45f),
                radius = size.minDimension * 0.43f,
                center = center,
                style = Stroke(width = 2.dp.toPx())
            )
        }
        Icon(
            imageVector = Icons.Default.FormatQuote,
            contentDescription = "Commonplace Literary Seal",
            tint = primaryColor,
            modifier = Modifier.size(44.dp)
        )
    }
}
